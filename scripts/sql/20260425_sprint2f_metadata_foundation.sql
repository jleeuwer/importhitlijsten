-- Sprint 2F-A — Metadatafundament hitlijsten
-- Adds managed metadata dimensions for omroep/zender and hitlijst period.
-- Idempotent: safe to run multiple times.

CREATE TABLE IF NOT EXISTS public.omroepen (
  omroep_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  omroep_code varchar(40) NOT NULL UNIQUE,
  omroep_naam varchar(150) NOT NULL UNIQUE,
  omroep_land varchar(2),
  omroep_actief boolean NOT NULL DEFAULT true,
  omroep_opmerking text,
  sort_order integer NOT NULL DEFAULT 999,
  created_at timestamp NOT NULL DEFAULT now(),
  updated_at timestamp NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.hitlijst_perioden (
  periode_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periode_code varchar(40) NOT NULL UNIQUE,
  periode_naam varchar(150) NOT NULL UNIQUE,
  periode_type varchar(30) NOT NULL,
  start_jaar integer,
  eind_jaar integer,
  actief boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 999,
  created_at timestamp NOT NULL DEFAULT now(),
  updated_at timestamp NOT NULL DEFAULT now(),
  CONSTRAINT hitlijst_perioden_type_chk CHECK (periode_type IN ('UNKNOWN','DECADE','ALLTIME','YEAR','THEME','GENRE','OTHER')),
  CONSTRAINT hitlijst_perioden_range_chk CHECK (
    (start_jaar IS NULL AND eind_jaar IS NULL) OR
    (start_jaar IS NOT NULL AND eind_jaar IS NOT NULL AND start_jaar <= eind_jaar)
  )
);

