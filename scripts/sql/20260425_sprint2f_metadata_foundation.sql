ALTER TABLE public.staging_hitlijsten
  ADD COLUMN IF NOT EXISTS omroep_key integer,
  ADD COLUMN IF NOT EXISTS periode_key integer;

ALTER TABLE public.hitlijsten
  ADD COLUMN IF NOT EXISTS omroep_key integer,
  ADD COLUMN IF NOT EXISTS periode_key integer;

DO $$
DECLARE
  v_unknown_omroep integer;
  v_unknown_periode integer;
BEGIN
  SELECT omroep_key INTO v_unknown_omroep FROM public.omroepen WHERE omroep_code = 'ONBEKEND';
  SELECT periode_key INTO v_unknown_periode FROM public.hitlijst_perioden WHERE periode_code = 'ONBEKEND';

  UPDATE public.staging_hitlijsten SET omroep_key = v_unknown_omroep WHERE omroep_key IS NULL;
  UPDATE public.staging_hitlijsten SET periode_key = v_unknown_periode WHERE periode_key IS NULL;
  UPDATE public.hitlijsten SET omroep_key = v_unknown_omroep WHERE omroep_key IS NULL;
  UPDATE public.hitlijsten SET periode_key = v_unknown_periode WHERE periode_key IS NULL;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'staging_hitlijsten_omroep_fk'
  ) THEN
    ALTER TABLE public.staging_hitlijsten
      ADD CONSTRAINT staging_hitlijsten_omroep_fk FOREIGN KEY (omroep_key) REFERENCES public.omroepen(omroep_key);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'staging_hitlijsten_periode_fk'
  ) THEN
    ALTER TABLE public.staging_hitlijsten
      ADD CONSTRAINT staging_hitlijsten_periode_fk FOREIGN KEY (periode_key) REFERENCES public.hitlijst_perioden(periode_key);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'hitlijsten_omroep_fk'
  ) THEN
    ALTER TABLE public.hitlijsten
      ADD CONSTRAINT hitlijsten_omroep_fk FOREIGN KEY (omroep_key) REFERENCES public.omroepen(omroep_key);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'hitlijsten_periode_fk'
  ) THEN
    ALTER TABLE public.hitlijsten
      ADD CONSTRAINT hitlijsten_periode_fk FOREIGN KEY (periode_key) REFERENCES public.hitlijst_perioden(periode_key);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS staging_hitlijsten_omroep_idx ON public.staging_hitlijsten(omroep_key);
CREATE INDEX IF NOT EXISTS staging_hitlijsten_periode_idx ON public.staging_hitlijsten(periode_key);
CREATE INDEX IF NOT EXISTS hitlijsten_omroep_idx ON public.hitlijsten(omroep_key);
CREATE INDEX IF NOT EXISTS hitlijsten_periode_idx ON public.hitlijsten(periode_key);
